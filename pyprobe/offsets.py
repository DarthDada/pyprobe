#: Fallback version used when the target CPython version is not in
#: ``_VERIFIED_OFFSETS``. Promoted to public (TODO §8.2) because
#: ``stack_dump`` and ``sampler`` read it across module boundaries.
DEFAULT_VERSION = "3.12"

_active = None


def _version_key(version_str):
    parts = version_str.split(".")
    if len(parts) >= 2:
        return f"{parts[0]}.{parts[1]}"
    return version_str


def supported_versions():
    return sorted(_VERIFIED_OFFSETS.keys())


def configure(version_str):
    """Configure the active offsets table for ``version_str``.

    Verified versions populate ``_active`` directly.  Unverified versions
    still populate ``_active`` with the :data:`DEFAULT_VERSION` fallback
    (so callers that catch :class:`VersionNotSupported` can keep using
    ``get`` / ``get_or`` immediately) and then raise — the caller decides
    whether to surface the warning.  No printing happens here (TODO §8.5).

    The development-time ``offsets.json`` override is applied only when its
    ``_version`` key matches the *requested* version_str's major.minor — so
    an unverified version with a matching override becomes effectively
    verified for the local dev session.
    """
    global _active
    key = _version_key(version_str)
    verified = _VERIFIED_OFFSETS.get(key)
    unverified_warning = None
    if verified is not None:
        _active = dict(verified)
    else:
        _active = dict(_VERIFIED_OFFSETS[DEFAULT_VERSION])
        unverified_warning = VersionNotSupported(version_str, DEFAULT_VERSION)

    # Development-time override: offsets.json is only applied when its
    # ``_version`` key matches the *requested* major.minor.  For an
    # unverified version with a matching override the data takes effect
    # before the raise, so a dev-only offsets.json is effectively the
    # verification evidence for the local session.
    path = os.path.join(os.path.dirname(__file__), "offsets.json")
    if os.path.exists(path):
        with open(path) as f:
            data = json.load(f)
        if data.pop("_version", None) == key:
            _active.update(data)

    if unverified_warning is not None:
        raise unverified_warning


def get(name):
    if _active is None:
        configure(DEFAULT_VERSION)
    return _active[name]


def get_or(name, default=None):
    """Like get(), but returns ``default`` for keys absent in this version.

    Keys whose struct field does not exist in a CPython version are omitted
    from that version's table; callers use this to branch on availability.
    """
    if _active is None:
        configure(DEFAULT_VERSION)
    return _active.get(name, default)
