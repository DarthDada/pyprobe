"""CPython struct offsets — verified per-version, with fallback for unverified versions.

Verified offset tables are keyed by CPython major.minor version. For 64-bit
LP64 architectures (x86-64, aarch64) the offsets are identical for the same
CPython version, so no architecture key is needed.

At runtime, call ``configure(version_str)`` with the target process's CPython
version. If the version is unverified, a warning is printed to stderr and the
default version's offsets are used as fallback — output may be incorrect.

``offsets.json`` (generated by ``tools/gen_offsets.c`` via
``scripts/gen_offsets.sh``) serves as a development-time override: if present
alongside this module, its values override the verified table. This allows
testing newly generated offsets before promoting them to ``_VERIFIED_OFFSETS``.
"""
