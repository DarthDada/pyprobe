_DEFAULT_VERSION = "3.12"

_active = None


def _version_key(version_str):
    parts = version_str.split(".")
    if len(parts) >= 2:
        return f"{parts[0]}.{parts[1]}"
    return version_str


def supported_versions():
    return sorted(_VERIFIED_OFFSETS.keys())


def configure(version_str):
    global _active
    key = _version_key(version_str)
    if key in _VERIFIED_OFFSETS:
        _active = dict(_VERIFIED_OFFSETS[key])
    else:
        print(
            f"[!] Warning: CPython {version_str} is not a verified version. "
            f"Using {_DEFAULT_VERSION} offsets as fallback — output may be incorrect.",
            file=sys.stderr,
        )
        _active = dict(_VERIFIED_OFFSETS[_DEFAULT_VERSION])

    path = os.path.join(os.path.dirname(__file__), "offsets.json")
    if os.path.exists(path):
        with open(path) as f:
            _active.update(json.load(f))


def get(name):
    if _active is None:
        configure(_DEFAULT_VERSION)
    return _active[name]
